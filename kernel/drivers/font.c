/* Shown for any byte outside printable ASCII. */
static const char *const unknown_art =
    G7("#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####");

static uint8_t glyph_bits[96][FONT_GLYPH_H];   /* [95] = unknown */

static void convert(const char *art, uint8_t *out)
{
    for (int r = 0; r < FONT_GLYPH_H; r++) {
        uint8_t bits = 0;
        for (int c = 0; c < FONT_GLYPH_W; c++)
            if (art[r * FONT_GLYPH_W + c] == '#') bits |= (uint8_t)(1 << (FONT_GLYPH_W - 1 - c));
        out[r] = bits;
    }
}

void font_init(void)
{
    for (int i = 0; i < 95; i++) convert(glyph_art[i], glyph_bits[i]);
    convert(unknown_art, glyph_bits[95]);
}

const uint8_t *font_glyph(char c)
{
    unsigned char u = (unsigned char)c;
    if (u >= 32 && u < 127) return glyph_bits[u - 32];
    return glyph_bits[95];
}
